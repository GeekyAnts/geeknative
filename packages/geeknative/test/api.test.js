import assert from 'node:assert/strict'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { test } from 'node:test'
import { generate } from '../src/codegen/index.js'
import { CliError } from '../src/lib/log.js'
import { editJson, outputOf, tempProject } from './helpers.js'

const MODELS = `export interface Story {
  id: string
  title: string
  score?: number
}
`

const OPERATIONS = `import type { Story } from './models'

export const api = {
  listStories: {
    method: 'GET',
    path: '/stories',
    response: null as unknown as Story[],
  },
  getStory: {
    method: 'GET',
    path: '/stories/:id',
    params: null as unknown as { id: string },
    response: null as unknown as Story,
  },
} as const
`

function projectWithApi(files = { 'models.ts': MODELS, 'operations.ts': OPERATIONS }) {
  const dir = tempProject()
  mkdirSync(path.join(dir, 'contracts', 'api'))
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(path.join(dir, 'contracts', 'api', name), content)
  }
  editJson(path.join(dir, 'contracts', 'config.json'), (config) => {
    config.values = {
      apiBaseUrl: {
        type: 'url',
        description: 'Backend API.',
        development: 'http://localhost:8080',
        staging: 'https://staging.example.com',
        production: 'https://api.example.com',
      },
    }
  })
  return dir
}

test('missing contracts/api produces no API outputs', () => {
  const paths = generate(tempProject()).map((o) => o.path)
  assert.equal(paths.some((p) => p.includes('ApiModels') || p.includes('/api')), false)
})

test('HN TypeScript contract generates models, clients, and copied web sources', () => {
  const outputs = generate(projectWithApi())

  const swiftModels = outputOf(outputs, 'ApiModels.swift')
  assert.match(swiftModels, /struct Story/)
  assert.match(swiftModels, /var id: String/)
  assert.match(swiftModels, /var score: Double\?/)

  const swiftClient = outputOf(outputs, 'ApiClient.swift')
  assert.match(swiftClient, /static func listStories\(\) async throws -> \[Story\]/)
  assert.match(swiftClient, /static func getStory\(id: String\) async throws -> Story/)
  assert.match(swiftClient, /AppConfig\.apiBaseUrl/)

  const kotlinModels = outputOf(outputs, 'ApiModels.kt')
  assert.match(kotlinModels, /data class Story/)
  assert.match(kotlinModels, /val id: String/)
  assert.match(kotlinModels, /val score: Double\? = null/)

  const kotlinClient = outputOf(outputs, 'ApiClient.kt')
  assert.match(kotlinClient, /suspend fun listStories\(\): List<Story>/)
  assert.match(kotlinClient, /suspend fun getStory\(id: String\): Story/)

  const copiedModels = outputOf(outputs, 'generated/api/models.ts')
  assert.match(copiedModels, /GENERATED by geeknative from contracts\/api\/models.ts/)
  assert.match(copiedModels, /export interface Story/)

  const copiedOps = outputOf(outputs, 'generated/api/operations.ts')
  assert.match(copiedOps, /listStories/)
  assert.match(copiedOps, /path: '\/stories\/:id'/)

  const client = outputOf(outputs, 'generated/api/client.ts')
  assert.match(client, /export async function listStories/)
  assert.match(client, /export async function getStory/)
  assert.match(client, /AppConfig\.apiBaseUrl/)
  assert.match(client, /import type \{ Story \} from "\.\/models"/)

  const barrel = outputOf(outputs, 'generated/api.ts')
  assert.match(barrel, /export \* from "\.\/api\/client"/)
})

test('contracts/api without apiBaseUrl fails clearly', () => {
  const dir = tempProject()
  mkdirSync(path.join(dir, 'contracts', 'api'))
  writeFileSync(path.join(dir, 'contracts', 'api', 'models.ts'), MODELS)
  assert.throws(() => generate(dir), (error) => {
    assert.ok(error instanceof CliError)
    assert.match(error.message, /apiBaseUrl/)
    return true
  })
})

test('a type error in the contract fails gen', () => {
  const dir = projectWithApi({
    'models.ts': `export interface Story {
  id: string
}

const check: Story = { id: 1 }
`,
  })
  assert.throws(() => generate(dir), (error) => {
    assert.ok(error instanceof CliError)
    assert.match(error.message, /contracts\/api\/models\.ts/)
    return true
  })
})

test('classes are rejected', () => {
  const dir = projectWithApi({
    'models.ts': `export class Story {
  id = ""
}
`,
  })
  assert.throws(() => generate(dir), (error) => {
    assert.ok(error instanceof CliError)
    assert.match(error.message, /classes are not allowed/)
    return true
  })
})

test('any is rejected', () => {
  const dir = projectWithApi({
    'models.ts': `export interface Story {
  id: any
}
`,
  })
  assert.throws(() => generate(dir), (error) => {
    assert.ok(error instanceof CliError)
    assert.match(error.message, /any/)
    return true
  })
})

test('removing contracts/api stops producing API files', () => {
  const dir = projectWithApi()
  const withApi = generate(dir).map((o) => o.path)
  assert.ok(withApi.some((p) => p.endsWith('ApiModels.swift')))

  rmSync(path.join(dir, 'contracts', 'api'), { recursive: true, force: true })
  const withoutApi = generate(dir).map((o) => o.path)
  assert.equal(withoutApi.some((p) => p.includes('ApiModels') || /\/api(\/|\.ts$)/.test(p)), false)
})
