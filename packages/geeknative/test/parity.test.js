import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { test } from 'node:test'
import { parity } from '../src/commands/parity.js'
import { tempDir } from './helpers.js'

/** @param {string} root @param {string} file @param {string} content */
function write(root, file, content) {
  mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
  writeFileSync(path.join(root, file), content)
}

const NOTES_SPEC = `---
id: notes
title: Notes
status:
  ios: done
  android: in-progress   # waiting on the empty state
  web: n/a
---

# Notes

## Acceptance criteria

- AC-notes-1: Notes are listed newest first.
- **AC-notes-2**: Deleting a note asks for confirmation.
- AC-notes-3: The empty state explains how to add a note.
`

test('parity shows each platform\'s status and which criteria its tests cover', () => {
  const root = tempDir()
  write(root, 'spec/features/notes.md', NOTES_SPEC)
  write(root, 'spec/features/_draft.md', '- AC-draft-1: ignored, files starting with _ are skipped')
  write(root, 'apps/ios/AppTests/NotesTests.swift', '@Test("AC-notes-1: newest first") func a() {}\n@Test("AC-notes-2: confirm") func b() {}')
  write(root, 'apps/ios/App/Features/Notes/NotesScreen.swift', '// AC-notes-3 mentioned in app code does not count as a test')
  write(root, 'apps/android/app/src/test/kotlin/app/NotesTest.kt', 'fun `AC-notes-1 newest first`() {}')
  write(root, 'apps/web/src/features/notes/notes.test.ts', "test('AC-notes-1: newest first', () => {})")

  parity(root)
  const md = readFileSync(path.join(root, 'spec', 'parity.md'), 'utf8')

  assert.match(md, /^<!-- GENERATED by `make parity`/)
  assert.match(md, /\| \[Notes\]\(features\/notes\.md\) \| ✅ done · 2\/3 tested \| 🚧 in progress · 1\/3 tested \| ➖ n\/a \|/)
  assert.match(md, /\| AC-notes-1: Notes are listed newest first\. \| ✅ \| ✅ \| ➖ \|/)
  assert.match(md, /\| AC-notes-2: Deleting a note asks for confirmation\. \| ✅ \| ❌ \| ➖ \|/)
  assert.match(md, /\| AC-notes-3: The empty state explains how to add a note\. \| ❌ \| ❌ \| ➖ \|/)
  assert.doesNotMatch(md, /draft/i)
})

test('parity handles a feature with no acceptance criteria yet', () => {
  const root = tempDir()
  write(root, 'spec/features/search.md', '---\nid: search\ntitle: Search\nstatus:\n  ios: planned\n  android: planned\n  web: planned\n---\n# Search\n')
  parity(root)
  const md = readFileSync(path.join(root, 'spec', 'parity.md'), 'utf8')
  assert.match(md, /\| \[Search\]\(features\/search\.md\) \| ⏳ planned \| ⏳ planned \| ⏳ planned \|/)
})
