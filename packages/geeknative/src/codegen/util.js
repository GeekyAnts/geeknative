/** Identifiers that would break generated Swift, Kotlin or TypeScript. */
const RESERVED = new Set(
  (
    'as any break case catch class continue default defer delete do else enum export extension false fun func ' +
    'function if import in init interface internal is let new nil null object operator package private protocol ' +
    'public repeat return self some static struct super switch this throw true try typealias typeof val var void ' +
    'when where while with yield'
  ).split(' '),
)

/**
 * Throws if `name` can't be used as an identifier on every platform.
 * @param {string} name
 * @param {string} where e.g. "contracts/tokens.json color"
 */
export function assertIdentifier(name, where) {
  if (!/^[a-z][a-zA-Z0-9]*$/.test(name)) {
    throw new CliError(`${where} "${name}": names must be camelCase letters and digits, starting lowercase.`)
  }
  if (RESERVED.has(name)) {
    throw new CliError(`${where} "${name}" is a reserved word in Swift, Kotlin or TypeScript. Pick another name.`)
  }
}

/** "settings.about.appVersion" → "settingsAboutAppVersion" @param {string} key */
export const camelKey = (key) =>
  key
    .split('.')
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('')

/** "settings.about.appVersion" → "settings_about_app_version" @param {string} key */
export const snakeKey = (key) =>
  key
    .split('.')
    .map((part) => part.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase())
    .join('_')

/** "onSurfaceVariant" → "on-surface-variant" @param {string} name */
export const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

/** @param {string} text */
export function swiftString(text) {
  return `"${text
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t')
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f]/g, (c) => `\\u{${c.charCodeAt(0).toString(16)}}`)}"`
}

/** @param {string} text */
export function kotlinString(text) {
  return `"${text
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\$/g, '\\$')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t')}"`
}

/** Single-line doc comment text. @param {string} text */
export const docText = (text) => text.replace(/\s*\n\s*/g, ' ').replace(/\*\//g, '* /')

/**
 * Parses "#RRGGBB" or "#RRGGBBAA" into [r, g, b, a], each 0-255.
 * @param {unknown} value
 * @param {string} where
 * @returns {[number, number, number, number]}
 */
export function parseHex(value, where) {
  if (typeof value !== 'string' || !/^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(value)) {
    throw new CliError(`${where} must be a hex color like "#4F46E5" or "#4F46E5CC" (got ${JSON.stringify(value)}).`)
  }
  const hex = value.slice(1)
  const channel = (/** @type {number} */ i) => parseInt(hex.slice(i, i + 2), 16)
  return [channel(0), channel(2), channel(4), hex.length === 8 ? channel(6) : 255]
}

/** @param {number} n */
export const hex2 = (n) => n.toString(16).padStart(2, '0').toUpperCase()

/**
 * JSON formatted the way Xcode writes it (sorted keys, " : " separators), so Xcode
 * doesn't rewrite generated catalogs when the project is opened.
 * @param {unknown} value
 * @param {string} [indent]
 * @returns {string}
 */
export function xcodeJson(value, indent = '') {
  const next = `${indent}  `
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    return `[\n${value.map((item) => next + xcodeJson(item, next)).join(',\n')}\n${indent}]`
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    if (entries.length === 0) return '{}'
    return `{\n${entries.map(([k, v]) => `${next}${JSON.stringify(k)} : ${xcodeJson(v, next)}`).join(',\n')}\n${indent}}`
  }
  return JSON.stringify(value)
}
