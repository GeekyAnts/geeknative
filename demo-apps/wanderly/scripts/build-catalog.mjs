function templatesFor(destinationId, ids) {
  const byId = Object.fromEntries(places.filter((p) => p.destinationId === destinationId).map((p) => [p.id, p]))
  return ids.map((day, i) => ({
    title: `Day ${i + 1}`,
    items: day.map((placeId, idx) => ({
      placeId,
      startTime: ['09:00', '12:30', '16:00', '19:00'][idx] ?? '10:00',
      durationMinutes: byId[placeId]?.durationMinutes || 120,
    })),
  }))
}

