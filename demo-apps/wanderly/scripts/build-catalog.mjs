const destIds = new Set(destinations.map((d) => d.id))
const placeIds = new Set()
for (const p of places) {
  if (!destIds.has(p.destinationId)) throw new Error(`Bad dest ${p.destinationId} on ${p.id}`)
  if (placeIds.has(p.id)) throw new Error(`Duplicate place ${p.id}`)
  placeIds.add(p.id)
}
for (const d of destinations) {
  for (const day of d.itineraryTemplates) {
    for (const item of day.items) {
      if (!placeIds.has(item.placeId)) throw new Error(`Missing place ${item.placeId}`)
    }
  }
}

const trending = destinations.filter((d) => d.trending).map((d) => d.id)
if (trending.join() !== 'paris,bali,tokyo,dubai,london,rome,singapore') {
  throw new Error(`Trending order wrong: ${trending}`)
}
if (destinations.filter((d) => d.featured).length !== 1) throw new Error('Need one featured')
if (destinations.length < 10) throw new Error('Need 10 destinations')

